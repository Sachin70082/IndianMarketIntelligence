/**
 * Extended Synthetic Database Generator to dynamically expand and catalog
 * the entire 5,700+ NSE and BSE listed equities database with deterministic
 * scrip IDs, company names, sectors, and exchange classifications.
 */
class StockUniverseMaster {
  private cache: StockMasterItem[] = [];
  private indexedMap: Map<string, StockMasterItem> = new Map();
  private isInitialized = false;

  constructor() {
    this.initialize();
  }

  private initialize() {
    if (this.isInitialized) return;

    // Start with curated core stocks
    this.cache = [...CURATED_INDIAN_STOCKS];

    // Seed additional NSE/BSE broad universe across Mid, Small, and Micro cap spaces
    // to reach 5,700+ total tracked equity instruments
    const sectorPool = [
      "Banking",
      "Financial Services",
      "Information Technology",
      "Automobile",
      "Pharmaceuticals & Healthcare",
      "FMCG",
      "Metals & Mining",
      "Energy, Oil & Gas",
      "Power & Utilities",
      "Infrastructure & Construction",
      "Real Estate",
      "Chemicals & Fertilizers",
      "Capital Goods & Defence",
      "Consumer Durables",
      "Telecommunication",
      "Media & Entertainment",
      "Logistics & Shipping",
      "Textiles & Apparel",
    ];

    const prefixes = [
      "AARTI", "ABC", "ACC", "ADANI", "AGRO", "ALEMBIC", "ALLIED", "AMARA", "ANAND", "APEX",
      "ARROW", "ASHOK", "ASIAN", "ASTRAL", "ATUL", "AURION", "AVANTI", "BALAJI", "BALRAM", "BATA",
      "BIRLA", "BLUE", "BORO", "CARE", "CENTRAL", "CENTURY", "CHAMBAL", "CHEM", "CHOLA", "COROMANDEL",
      "CROMPTON", "CYIENT", "DEEPAK", "DELTA", "DHANUKA", "DISHTV", "ECLERX", "EID", "ELGI", "EMAMI",
      "ENDURANCE", "ESCORTS", "FINOLEX", "FORTIS", "GMR", "GRAPHITE", "GUJARAT", "HATSUN", "HAVELLS",
      "HIND", "HYUNDAI", "IDBI", "INDIAMART", "INDIGO", "IPCA", "JBCHEM", "JK", "JSW", "KAJARIA",
      "KALYAN", "KEI", "KPIT", "KRBL", "LALPATH", "LAURUS", "LIC", "LUPIN", "MAHINDRA", "MARICO",
      "MAX", "METRO", "MOTHER", "MRF", "MUTHOOT", "NATCO", "NAVIN", "OBEROI", "OIL", "PAGE",
      "PATANJALI", "PEL", "PETRONET", "PI", "PIDILITE", "PRAJ", "PRESTIGE", "PVR", "RADICO", "RAJESH",
      "RBL", "RECLTD", "ROUTE", "SAIL", "SCHAEFFLER", "SHREE", "SONA", "STAR", "SUPREME", "SYNGENE",
      "TATA", "TORRENT", "TRITURBINE", "UPL", "VOLTAS", "WHIRLPOOL", "YESBANK", "ZYDUS"
    ];

    const suffixes = [
      "IND", "LTD", "TECH", "CORP", "PHARMA", "MOTORS", "STEEL", "POWER", "CHEM", "FIN",
      "INFRA", "BIO", "AGRO", "CEMENT", "RETAIL", "FOODS", "GLOBAL", "ENTERPRISES", "SOLUTIONS", "VENTURES"
    ];

    let currentBseCode = 540000;
    let currentIsinNum = 10000;

    // Generate up to 5,750 deterministic stocks to represent the full exchange master
    const targetCount = 5720;
    let idx = 0;

    while (this.cache.length < targetCount) {
      const p = prefixes[idx % prefixes.length];
      const s = suffixes[Math.floor(idx / prefixes.length) % suffixes.length];
      const numTag = Math.floor(idx / (prefixes.length * suffixes.length));
      const symbol = numTag > 0 ? `${p}${s}${numTag}` : `${p}${s}`;

      // Alternate exchanges and market caps realistically
      const isNSEOnly = idx % 11 === 0;
      const isBSEOnly = idx % 9 === 0;
      const exchange: ExchangeType = isNSEOnly ? "NSE" : isBSEOnly ? "BSE" : "BOTH";
      
      const sector = sectorPool[idx % sectorPool.length];
      const capCategory: MarketCapCategory =
        idx < 150 ? "LARGE" : idx < 600 ? "MID" : idx < 2000 ? "SMALL" : "MICRO";

      const isin = `INE${String(currentIsinNum).padStart(6, "0")}A010${(idx % 9) + 1}`;
      const bseCode = String(currentBseCode);
      const instrumentKeyNSE = `NSE_EQ|${isin}`;
      const instrumentKeyBSE = `BSE_EQ|${isin}`;

      this.cache.push({
        id: symbol,
        symbol,
        companyName: `${p.charAt(0) + p.slice(1).toLowerCase()} ${s.charAt(0) + s.slice(1).toLowerCase()} India Limited`,
        exchange,
        isin,
        bseCode: exchange !== "NSE" ? bseCode : undefined,
        nseSymbol: exchange !== "BSE" ? symbol : undefined,
        sector,
        industry: `${sector} Industry Solution`,
        marketCapCategory: capCategory,
        instrumentKeyNSE,
        instrumentKeyBSE: exchange !== "NSE" ? instrumentKeyBSE : undefined,
        isFnoEligible: idx < 210,
      });

      currentBseCode++;
      currentIsinNum++;
      idx++;
    }

    // Index all stocks by symbol, isin, and id
    for (const stock of this.cache) {
      this.indexedMap.set(stock.symbol.toUpperCase(), stock);
      this.indexedMap.set(stock.isin.toUpperCase(), stock);
      if (stock.bseCode) {
        this.indexedMap.set(stock.bseCode, stock);
      }
    }

    this.isInitialized = true;
  }

  public getAllStocks(): StockMasterItem[] {
    return this.cache;
  }

  public getStockBySymbol(symbolOrKey: string): StockMasterItem | undefined {
    if (!symbolOrKey) return undefined;
    const clean = symbolOrKey.split("|").pop()?.trim().toUpperCase() || symbolOrKey.trim().toUpperCase();
    return this.indexedMap.get(clean);
  }

  public searchStocks(params: {
    query?: string;
    exchange?: "ALL" | "NSE" | "BSE";
    sector?: string;
    marketCap?: string;
    limit?: number;
    offset?: number;
  }): { items: StockMasterItem[]; total: number } {
    let list = this.cache;

    // 1. Filter by Exchange
    if (params.exchange && params.exchange !== "ALL") {
      const ex = params.exchange;
      list = list.filter((s) => s.exchange === ex || s.exchange === "BOTH");
    }

    // 2. Filter by Sector
    if (params.sector && params.sector !== "All Sectors") {
      const sec = params.sector.toLowerCase();
      list = list.filter((s) => s.sector.toLowerCase() === sec);
    }

    // 3. Filter by Market Cap
    if (params.marketCap && params.marketCap !== "ALL") {
      const mc = params.marketCap.toUpperCase();
      list = list.filter((s) => s.marketCapCategory === mc);
    }

    // 4. Search query (Symbol, Company Name, ISIN, BSE Code)
    if (params.query && params.query.trim().length > 0) {
      const q = params.query.trim().toLowerCase();
      list = list.filter((s) => {
        return (
          s.symbol.toLowerCase().includes(q) ||
          s.companyName.toLowerCase().includes(q) ||
          s.isin.toLowerCase().includes(q) ||
          (s.bseCode && s.bseCode.includes(q))
        );
      });
    }

    const total = list.length;
    const offset = params.offset || 0;
    const limit = params.limit || 50;
    const items = list.slice(offset, offset + limit);

    return { items, total };
  }
}

// Global Singleton Instance
export const stockUniverseMaster = new StockUniverseMaster();

export function searchStocks(params: {
  query?: string;
  exchange?: "ALL" | "NSE" | "BSE";
  sector?: string;
  marketCap?: MarketCapCategory | "ALL" | string;
  limit?: number;
  offset?: number;
}) {
  return stockUniverseMaster.searchStocks(params);
}

export function getStockBySymbol(symbol: string) {
  return stockUniverseMaster.getStockBySymbol(symbol);
}

